-- Laporan per kelas: pengetahuan + kepatuhan per minggu
CREATE VIEW laporan_kelas_v AS
SELECT k.kelas_id,
       k.nama_kelas,
       count(DISTINCT s.siswa_id) AS jumlah_siswa,
       round(avg(sp.skor_pretest), 1)  AS rata_pretest,
       round(avg(sp.skor_posttest), 1) AS rata_posttest,
       round(avg(sp.selisih), 1)       AS rata_selisih,
       (SELECT round(avg(km.persen_kepatuhan), 1)
          FROM kepatuhan_mingguan_v km
          JOIN siswa_m s2 ON s2.siswa_id = km.siswa_id
         WHERE s2.kelas_id = k.kelas_id AND km.minggu_ke = 1) AS kepatuhan_minggu_1,
       (SELECT round(avg(km.persen_kepatuhan), 1)
          FROM kepatuhan_mingguan_v km
          JOIN siswa_m s2 ON s2.siswa_id = km.siswa_id
         WHERE s2.kelas_id = k.kelas_id AND km.minggu_ke = 2) AS kepatuhan_minggu_2,
       (SELECT round(avg(km.persen_kepatuhan), 1)
          FROM kepatuhan_mingguan_v km
          JOIN siswa_m s2 ON s2.siswa_id = km.siswa_id
         WHERE s2.kelas_id = k.kelas_id AND km.minggu_ke = 3) AS kepatuhan_minggu_3
FROM kelas_m k
LEFT JOIN siswa_m s ON s.kelas_id = k.kelas_id
LEFT JOIN skor_pengetahuan_v sp ON sp.siswa_id = s.siswa_id
GROUP BY k.kelas_id, k.nama_kelas;

-- Pola konsumsi: % siswa yang makan >=3x/minggu minimal satu bahan dalam kelompok
CREATE VIEW pola_konsumsi_kelompok_v AS
SELECT k.kelas_id,
       kb.kelompok_bahan_id,
       kb.kode AS kelompok_kode,
       kb.nama AS kelompok_nama,
       count(DISTINCT x.siswa_id) AS jumlah_responden,
       count(DISTINCT x.siswa_id) FILTER (WHERE x.sering) AS jumlah_sering,
       round(100.0 * count(DISTINCT x.siswa_id) FILTER (WHERE x.sering)
             / NULLIF(count(DISTINCT x.siswa_id), 0), 1) AS persen_sering_3x_minggu
FROM (
    SELECT sq.siswa_id,
           bm.kelompok_bahan_id,
           bool_or(f.kali_per_minggu >= 3) AS sering
    FROM sqffq_t sq
    JOIN sqffq_detail_t d     ON d.sqffq_id = sq.sqffq_id
    JOIN bahan_makanan_m bm   ON bm.bahan_makanan_id = d.bahan_makanan_id
    JOIN frekuensi_m f        ON f.frekuensi_id = d.frekuensi_id
    WHERE sq.status = 'SELESAI'
    GROUP BY sq.siswa_id, bm.kelompok_bahan_id
) x
JOIN siswa_m s          ON s.siswa_id = x.siswa_id
JOIN kelas_m k          ON k.kelas_id = s.kelas_id
JOIN kelompok_bahan_m kb ON kb.kelompok_bahan_id = x.kelompok_bahan_id
GROUP BY k.kelas_id, kb.kelompok_bahan_id, kb.kode, kb.nama;

-- Tempat sarapan per kelas (dari food record)
CREATE VIEW tempat_sarapan_v AS
SELECT k.kelas_id,
       tm.tempat_makan_id,
       tm.nama AS tempat,
       count(*) AS jumlah_catatan,
       round(100.0 * count(*) / NULLIF(sum(count(*)) OVER (PARTITION BY k.kelas_id), 0), 1) AS persen
FROM food_record_t fr
JOIN peserta_program_t pp ON pp.peserta_program_id = fr.peserta_program_id
JOIN siswa_m s            ON s.siswa_id = pp.siswa_id
JOIN kelas_m k            ON k.kelas_id = s.kelas_id
JOIN tempat_makan_m tm    ON tm.tempat_makan_id = fr.tempat_makan_id
WHERE NOT fr.tidak_sarapan
GROUP BY k.kelas_id, tm.tempat_makan_id, tm.nama;

