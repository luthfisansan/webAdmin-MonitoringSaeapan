-- 5. FUNGSI & TRIGGER: perpindahan status akun
--    PRETEST -> EDUKASI -> MENUNGGU_VERIFIKASI -> TERVERIFIKASI
-- =====================================================================

-- Pindahkan status hanya bila status saat ini = p_dari; catat ke riwayat.
CREATE FUNCTION fn_set_status_akun(
    p_siswa_id BIGINT,
    p_dari     VARCHAR,
    p_ke       VARCHAR,
    p_oleh     BIGINT DEFAULT NULL,
    p_catatan  TEXT   DEFAULT NULL
) RETURNS BOOLEAN
LANGUAGE plpgsql AS $$
DECLARE
    v_dari BIGINT;
    v_ke   BIGINT;
    v_baris INTEGER;
BEGIN
    SELECT status_akun_id INTO v_dari FROM status_akun_m WHERE kode = p_dari;
    SELECT status_akun_id INTO v_ke   FROM status_akun_m WHERE kode = p_ke;

    UPDATE siswa_m
       SET status_akun_id = v_ke, diubah_pada = now()
     WHERE siswa_id = p_siswa_id AND status_akun_id = v_dari;
    GET DIAGNOSTICS v_baris = ROW_COUNT;

    IF v_baris = 0 THEN
        RETURN FALSE;
    END IF;

    INSERT INTO riwayat_status_akun_t (siswa_id, status_akun_id, diubah_oleh_pengguna_id, catatan)
    VALUES (p_siswa_id, v_ke, p_oleh, p_catatan);
    RETURN TRUE;
END;
$$;

-- MENUNGGU_VERIFIKASI -> TERVERIFIKASI bila SQ-FFQ sudah SELESAI; sekaligus
-- mendaftarkan siswa ke program aktif (3 minggu sejak hari ini / awal program).
CREATE FUNCTION fn_verifikasi_siswa(p_siswa_id BIGINT) RETURNS VOID
LANGUAGE plpgsql AS $$
DECLARE
    v_petugas BIGINT;
BEGIN
    SELECT sq.petugas_pengguna_id INTO v_petugas
      FROM sqffq_t sq
     WHERE sq.siswa_id = p_siswa_id AND sq.tahap = 'AWAL' AND sq.status = 'SELESAI';

    IF v_petugas IS NULL THEN
        RETURN;
    END IF;

    IF fn_set_status_akun(p_siswa_id, 'MENUNGGU_VERIFIKASI', 'TERVERIFIKASI',
                          v_petugas, 'SQ-FFQ selesai diisi petugas') THEN
        UPDATE siswa_m
           SET terverifikasi_pada = now(),
               terverifikasi_oleh_pengguna_id = v_petugas
         WHERE siswa_id = p_siswa_id;

        INSERT INTO peserta_program_t (siswa_id, program_id, tanggal_mulai, tanggal_selesai)
        SELECT p_siswa_id,
               p.program_id,
               GREATEST(CURRENT_DATE, p.tanggal_mulai),
               GREATEST(CURRENT_DATE, p.tanggal_mulai) + (p.durasi_minggu * 7 - 1)
          FROM program_m p
         WHERE p.aktif
         ORDER BY p.tanggal_mulai DESC
         LIMIT 1
        ON CONFLICT (siswa_id, program_id) DO NOTHING;
    END IF;
END;
$$;

-- EDUKASI -> MENUNGGU_VERIFIKASI bila semua materi wajib sudah dibaca.
CREATE FUNCTION fn_cek_edukasi_selesai(p_siswa_id BIGINT) RETURNS VOID
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
          FROM materi_edukasi_m m
         WHERE m.wajib AND m.aktif
           AND NOT EXISTS (
               SELECT 1 FROM baca_materi_t b
                WHERE b.siswa_id = p_siswa_id
                  AND b.materi_edukasi_id = m.materi_edukasi_id
                  AND b.selesai)
    ) THEN
        IF fn_set_status_akun(p_siswa_id, 'EDUKASI', 'MENUNGGU_VERIFIKASI',
                              NULL, 'Semua materi wajib sudah dibaca') THEN
            -- jika petugas sudah lebih dulu menyelesaikan SQ-FFQ
            PERFORM fn_verifikasi_siswa(p_siswa_id);
        END IF;
    END IF;
END;
$$;

-- Pretest selesai -> status EDUKASI
CREATE FUNCTION trg_hasil_kuesioner_fn() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_jenis VARCHAR;
BEGIN
    SELECT jenis INTO v_jenis FROM kuesioner_m WHERE kuesioner_id = NEW.kuesioner_id;
    IF v_jenis = 'PRETEST' THEN
        IF fn_set_status_akun(NEW.siswa_id, 'PRETEST', 'EDUKASI', NULL, 'Pretest selesai') THEN
            -- bila belum ada materi wajib, langsung lanjut
            PERFORM fn_cek_edukasi_selesai(NEW.siswa_id);
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER hasil_kuesioner_selesai_trg
AFTER INSERT OR UPDATE OF selesai_pada ON hasil_kuesioner_t
FOR EACH ROW WHEN (NEW.selesai_pada IS NOT NULL)
EXECUTE FUNCTION trg_hasil_kuesioner_fn();

-- Materi wajib selesai dibaca -> cek apakah semua sudah dibaca
CREATE FUNCTION trg_baca_materi_fn() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    PERFORM fn_cek_edukasi_selesai(NEW.siswa_id);
    RETURN NEW;
END;
$$;

CREATE TRIGGER baca_materi_selesai_trg
AFTER INSERT OR UPDATE OF selesai ON baca_materi_t
FOR EACH ROW WHEN (NEW.selesai)
EXECUTE FUNCTION trg_baca_materi_fn();

-- SQ-FFQ selesai -> verifikasi akun
CREATE FUNCTION trg_sqffq_fn() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.selesai_pada IS NULL THEN
        UPDATE sqffq_t SET selesai_pada = now() WHERE sqffq_id = NEW.sqffq_id;
    END IF;
    IF NEW.tahap = 'AWAL' THEN
        PERFORM fn_verifikasi_siswa(NEW.siswa_id);
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER sqffq_selesai_trg
AFTER INSERT OR UPDATE OF status ON sqffq_t
FOR EACH ROW WHEN (NEW.status = 'SELESAI')
EXECUTE FUNCTION trg_sqffq_fn();

