-- =====================================================================
-- Breakfast Planner - skema database (PostgreSQL 14+)
--
-- Konvensi
--   * Tabel master    : akhiran _m   (data referensi / pengaturan)
--   * Tabel transaksi : akhiran _t   (data yang dihasilkan pengguna)
--   * View            : akhiran _v
--   * Primary key     : <nama>_id  (kata "id" selalu di belakang)
--   * Foreign key     : memakai nama kolom yang SAMA dengan PK yang dituju,
--                       kecuali bila satu tabel merujuk tabel yang sama
--                       lebih dari sekali (diberi awalan peran, tetap
--                       berakhiran _id), mis. petugas_pengguna_id.
--
-- Alur status akun siswa (status_akun_m):
--   PRETEST -> EDUKASI -> MENUNGGU_VERIFIKASI -> TERVERIFIKASI
--   * PRETEST             : baru registrasi, belum menyelesaikan pretest
--   * EDUKASI             : pretest selesai, wajib membaca materi edukasi
--   * MENUNGGU_VERIFIKASI : semua materi wajib dibaca, menunggu petugas
--                           mengisi SQ-FFQ di web admin
--   * TERVERIFIKASI       : SQ-FFQ selesai diisi petugas -> Beranda terbuka
--   Perpindahan status dijalankan oleh trigger di bagian akhir berkas ini.
-- =====================================================================

BEGIN;

-- =====================================================================
-- 1. TABEL MASTER (_m)
-- =====================================================================

CREATE TABLE peran_m (
    peran_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode          VARCHAR(20) NOT NULL UNIQUE,
    nama          VARCHAR(50) NOT NULL
);

CREATE TABLE status_akun_m (
    status_akun_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode           VARCHAR(30) NOT NULL UNIQUE,
    nama           VARCHAR(60) NOT NULL,
    urutan         SMALLINT NOT NULL UNIQUE
);

CREATE TABLE kelas_m (
    kelas_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_kelas    VARCHAR(20) NOT NULL,
    tahun_ajaran  VARCHAR(9)  NOT NULL,          -- contoh: 2026/2027
    aktif         BOOLEAN     NOT NULL DEFAULT TRUE,
    UNIQUE (nama_kelas, tahun_ajaran)
);

-- Akun login (siswa maupun petugas web admin)
CREATE TABLE pengguna_m (
    pengguna_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    peran_id           BIGINT NOT NULL REFERENCES peran_m (peran_id),
    email              VARCHAR(150) NOT NULL,
    kata_sandi_hash    VARCHAR(255) NOT NULL,
    nama_lengkap       VARCHAR(120) NOT NULL,
    aktif              BOOLEAN NOT NULL DEFAULT TRUE,
    terakhir_login_pada TIMESTAMPTZ,
    dibuat_pada        TIMESTAMPTZ NOT NULL DEFAULT now(),
    diubah_pada        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX pengguna_m_email_uq ON pengguna_m (lower(email));
CREATE INDEX pengguna_m_peran_ix ON pengguna_m (peran_id);

-- Profil siswa (1 pengguna berperan SISWA = 1 baris)
CREATE TABLE siswa_m (
    siswa_id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pengguna_id                    BIGINT NOT NULL UNIQUE REFERENCES pengguna_m (pengguna_id),
    kelas_id                       BIGINT NOT NULL REFERENCES kelas_m (kelas_id),
    status_akun_id                 BIGINT NOT NULL REFERENCES status_akun_m (status_akun_id),
    jenis_kelamin                  CHAR(1) CHECK (jenis_kelamin IN ('L', 'P')),   -- opsional
    tanggal_lahir                  DATE,                                           -- opsional
    terverifikasi_pada             TIMESTAMPTZ,
    terverifikasi_oleh_pengguna_id BIGINT REFERENCES pengguna_m (pengguna_id),
    dibuat_pada                    TIMESTAMPTZ NOT NULL DEFAULT now(),
    diubah_pada                    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX siswa_m_kelas_ix  ON siswa_m (kelas_id);
CREATE INDEX siswa_m_status_ix ON siswa_m (status_akun_id);

-- Periode program intervensi (mis. 3 minggu)
CREATE TABLE program_m (
    program_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_program    VARCHAR(120) NOT NULL,
    tanggal_mulai   DATE NOT NULL,
    durasi_minggu   SMALLINT NOT NULL DEFAULT 3 CHECK (durasi_minggu > 0),
    aktif           BOOLEAN NOT NULL DEFAULT TRUE
);

-- Bank soal pretest / post test
CREATE TABLE kuesioner_m (
    kuesioner_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jenis         VARCHAR(10) NOT NULL CHECK (jenis IN ('PRETEST', 'POSTTEST')),
    judul         VARCHAR(150) NOT NULL,
    aktif         BOOLEAN NOT NULL DEFAULT TRUE
);
-- hanya satu kuesioner aktif per jenis
CREATE UNIQUE INDEX kuesioner_m_jenis_aktif_uq ON kuesioner_m (jenis) WHERE aktif;

CREATE TABLE soal_m (
    soal_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kuesioner_id  BIGINT NOT NULL REFERENCES kuesioner_m (kuesioner_id),
    nomor         SMALLINT NOT NULL,
    teks_soal     TEXT NOT NULL,
    UNIQUE (kuesioner_id, nomor)
);

CREATE TABLE opsi_jawaban_m (
    opsi_jawaban_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    soal_id         BIGINT NOT NULL REFERENCES soal_m (soal_id),
    kode_opsi       CHAR(1) NOT NULL,
    teks_opsi       TEXT NOT NULL,
    benar           BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (soal_id, kode_opsi)
);
-- tepat satu opsi benar per soal
CREATE UNIQUE INDEX opsi_jawaban_m_benar_uq ON opsi_jawaban_m (soal_id) WHERE benar;

-- Materi edukasi (wajib dibaca setelah pretest)
CREATE TABLE materi_edukasi_m (
    materi_edukasi_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judul             VARCHAR(150) NOT NULL,
    ringkasan         VARCHAR(255),
    konten            TEXT,
    urutan            SMALLINT NOT NULL DEFAULT 1,
    wajib             BOOLEAN NOT NULL DEFAULT TRUE,
    aktif             BOOLEAN NOT NULL DEFAULT TRUE,
    dibuat_pada       TIMESTAMPTZ NOT NULL DEFAULT now(),
    diubah_pada       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- SQ-FFQ: kelompok & bahan makanan (sesuai formulir SQ-FFQ)
CREATE TABLE kelompok_bahan_m (
    kelompok_bahan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode              CHAR(1) NOT NULL UNIQUE,      -- A..I
    nama              VARCHAR(60) NOT NULL,
    urutan            SMALLINT NOT NULL UNIQUE
);

CREATE TABLE bahan_makanan_m (
    bahan_makanan_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kelompok_bahan_id   BIGINT NOT NULL REFERENCES kelompok_bahan_m (kelompok_bahan_id),
    nama_bahan          VARCHAR(80) NOT NULL,
    urutan              SMALLINT NOT NULL,
    porsi_standar_gram  NUMERIC(7,2),               -- kolom "Satu Porsi (g)" bila baku
    aktif               BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (kelompok_bahan_id, nama_bahan)
);
CREATE INDEX bahan_makanan_m_kelompok_ix ON bahan_makanan_m (kelompok_bahan_id);

-- Pilihan frekuensi konsumsi pada SQ-FFQ
CREATE TABLE frekuensi_m (
    frekuensi_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode             VARCHAR(20) NOT NULL UNIQUE,
    label            VARCHAR(40) NOT NULL,
    urutan           SMALLINT NOT NULL UNIQUE,
    kali_per_minggu  NUMERIC(6,2) NOT NULL,         -- konversi ke kali/minggu
    skor             NUMERIC(6,2)                   -- bobot untuk skor konsumsi pangan (food score)
);

-- Ukuran Rumah Tangga (URT) dan konversinya ke gram per bahan
CREATE TABLE urt_m (
    urt_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_urt  VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE konversi_urt_m (
    konversi_urt_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bahan_makanan_id BIGINT NOT NULL REFERENCES bahan_makanan_m (bahan_makanan_id),
    urt_id           BIGINT NOT NULL REFERENCES urt_m (urt_id),
    berat_gram       NUMERIC(7,2) NOT NULL CHECK (berat_gram > 0),
    UNIQUE (bahan_makanan_id, urt_id)
);

CREATE TABLE tempat_makan_m (
    tempat_makan_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode             VARCHAR(20) NOT NULL UNIQUE,
    nama             VARCHAR(40) NOT NULL
);

-- Status realisasi tiap item food record terhadap rencana
CREATE TABLE status_realisasi_m (
    status_realisasi_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode                VARCHAR(20) NOT NULL UNIQUE,
    nama                VARCHAR(40) NOT NULL
);

-- =====================================================================
-- 2. TABEL TRANSAKSI (_t)
-- =====================================================================

-- Riwayat perubahan status akun (audit)
CREATE TABLE riwayat_status_akun_t (
    riwayat_status_akun_id  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    siswa_id                BIGINT NOT NULL REFERENCES siswa_m (siswa_id),
    status_akun_id          BIGINT NOT NULL REFERENCES status_akun_m (status_akun_id),
    diubah_oleh_pengguna_id BIGINT REFERENCES pengguna_m (pengguna_id),   -- NULL = sistem
    catatan                 TEXT,
    dibuat_pada             TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX riwayat_status_akun_t_siswa_ix ON riwayat_status_akun_t (siswa_id, dibuat_pada);

-- Pretest / post test
CREATE TABLE hasil_kuesioner_t (
    hasil_kuesioner_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    siswa_id           BIGINT NOT NULL REFERENCES siswa_m (siswa_id),
    kuesioner_id       BIGINT NOT NULL REFERENCES kuesioner_m (kuesioner_id),
    mulai_pada         TIMESTAMPTZ NOT NULL DEFAULT now(),
    selesai_pada       TIMESTAMPTZ,
    jumlah_soal        SMALLINT,
    jumlah_benar       SMALLINT,
    skor               NUMERIC(5,2),                 -- skala 0-100
    UNIQUE (siswa_id, kuesioner_id)
);

CREATE TABLE jawaban_kuesioner_t (
    jawaban_kuesioner_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    hasil_kuesioner_id   BIGINT NOT NULL REFERENCES hasil_kuesioner_t (hasil_kuesioner_id) ON DELETE CASCADE,
    soal_id              BIGINT NOT NULL REFERENCES soal_m (soal_id),
    opsi_jawaban_id      BIGINT NOT NULL REFERENCES opsi_jawaban_m (opsi_jawaban_id),
    benar                BOOLEAN NOT NULL,
    UNIQUE (hasil_kuesioner_id, soal_id)
);

-- Materi edukasi yang sudah dibaca siswa
CREATE TABLE baca_materi_t (
    baca_materi_id     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    siswa_id           BIGINT NOT NULL REFERENCES siswa_m (siswa_id),
    materi_edukasi_id  BIGINT NOT NULL REFERENCES materi_edukasi_m (materi_edukasi_id),
    selesai            BOOLEAN NOT NULL DEFAULT FALSE,
    mulai_pada         TIMESTAMPTZ NOT NULL DEFAULT now(),
    selesai_pada       TIMESTAMPTZ,
    UNIQUE (siswa_id, materi_edukasi_id)
);

-- SQ-FFQ yang diisi petugas lewat web admin (wawancara)
CREATE TABLE sqffq_t (
    sqffq_id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    siswa_id             BIGINT NOT NULL REFERENCES siswa_m (siswa_id),
    petugas_pengguna_id  BIGINT NOT NULL REFERENCES pengguna_m (pengguna_id),
    tahap                VARCHAR(10) NOT NULL DEFAULT 'AWAL' CHECK (tahap IN ('AWAL', 'AKHIR')),
    status               VARCHAR(10) NOT NULL DEFAULT 'DRAF' CHECK (status IN ('DRAF', 'SELESAI')),
    tanggal_wawancara    DATE NOT NULL DEFAULT CURRENT_DATE,
    catatan              TEXT,
    selesai_pada         TIMESTAMPTZ,
    dibuat_pada          TIMESTAMPTZ NOT NULL DEFAULT now(),
    diubah_pada          TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (siswa_id, tahap)
);
CREATE INDEX sqffq_t_petugas_ix ON sqffq_t (petugas_pengguna_id);

CREATE TABLE sqffq_detail_t (
    sqffq_detail_id  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    sqffq_id         BIGINT NOT NULL REFERENCES sqffq_t (sqffq_id) ON DELETE CASCADE,
    bahan_makanan_id BIGINT NOT NULL REFERENCES bahan_makanan_m (bahan_makanan_id),
    frekuensi_id     BIGINT NOT NULL REFERENCES frekuensi_m (frekuensi_id),
    porsi_gram       NUMERIC(7,2) CHECK (porsi_gram IS NULL OR porsi_gram >= 0),
    UNIQUE (sqffq_id, bahan_makanan_id)
);

-- Keikutsertaan siswa pada program 3 minggu (dibuat saat terverifikasi)
CREATE TABLE peserta_program_t (
    peserta_program_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    siswa_id           BIGINT NOT NULL REFERENCES siswa_m (siswa_id),
    program_id         BIGINT NOT NULL REFERENCES program_m (program_id),
    tanggal_mulai      DATE NOT NULL,
    tanggal_selesai    DATE NOT NULL,
    status             VARCHAR(10) NOT NULL DEFAULT 'AKTIF' CHECK (status IN ('AKTIF', 'SELESAI')),
    dibuat_pada        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (siswa_id, program_id),
    CHECK (tanggal_selesai >= tanggal_mulai)
);

-- Planner: rencana sarapan (dibuat malam sebelumnya)
CREATE TABLE rencana_sarapan_t (
    rencana_sarapan_id  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    peserta_program_id  BIGINT NOT NULL REFERENCES peserta_program_t (peserta_program_id),
    tanggal_sarapan     DATE NOT NULL,
    jam_rencana         TIME,
    tempat_makan_id     BIGINT REFERENCES tempat_makan_m (tempat_makan_id),
    dibuat_pada         TIMESTAMPTZ NOT NULL DEFAULT now(),
    diubah_pada         TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (peserta_program_id, tanggal_sarapan)
);

CREATE TABLE rencana_sarapan_detail_t (
    rencana_sarapan_detail_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    rencana_sarapan_id        BIGINT NOT NULL REFERENCES rencana_sarapan_t (rencana_sarapan_id) ON DELETE CASCADE,
    nama_makanan              VARCHAR(100) NOT NULL,
    bahan_makanan_id          BIGINT REFERENCES bahan_makanan_m (bahan_makanan_id),
    urt_id                    BIGINT REFERENCES urt_m (urt_id),
    jumlah_urt                NUMERIC(6,2),
    urutan                    SMALLINT NOT NULL DEFAULT 1
);
CREATE INDEX rencana_sarapan_detail_t_rencana_ix ON rencana_sarapan_detail_t (rencana_sarapan_id);

-- Food record: realisasi sarapan (dicatat pagi hari)
CREATE TABLE food_record_t (
    food_record_id      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    peserta_program_id  BIGINT NOT NULL REFERENCES peserta_program_t (peserta_program_id),
    rencana_sarapan_id  BIGINT REFERENCES rencana_sarapan_t (rencana_sarapan_id),
    tanggal             DATE NOT NULL,
    jam_makan           TIME,
    tempat_makan_id     BIGINT REFERENCES tempat_makan_m (tempat_makan_id),
    tidak_sarapan       BOOLEAN NOT NULL DEFAULT FALSE,
    dibuat_pada         TIMESTAMPTZ NOT NULL DEFAULT now(),
    diubah_pada         TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (peserta_program_id, tanggal)
);
CREATE UNIQUE INDEX food_record_t_rencana_uq ON food_record_t (rencana_sarapan_id) WHERE rencana_sarapan_id IS NOT NULL;

-- Kolom sama dengan formulir food record: jenis makanan, bahan makanan, URT, gram, keterangan
CREATE TABLE food_record_detail_t (
    food_record_detail_id     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    food_record_id            BIGINT NOT NULL REFERENCES food_record_t (food_record_id) ON DELETE CASCADE,
    rencana_sarapan_detail_id BIGINT REFERENCES rencana_sarapan_detail_t (rencana_sarapan_detail_id),
    status_realisasi_id       BIGINT NOT NULL REFERENCES status_realisasi_m (status_realisasi_id),
    nama_makanan              VARCHAR(100) NOT NULL,      -- jenis makanan
    bahan_teks                VARCHAR(255),               -- bahan makanan (teks bebas)
    bahan_makanan_id          BIGINT REFERENCES bahan_makanan_m (bahan_makanan_id),
    urt_id                    BIGINT REFERENCES urt_m (urt_id),
    jumlah_urt                NUMERIC(6,2),
    berat_gram                NUMERIC(7,2),               -- otomatis dari konversi_urt_m bila tersedia
    keterangan                VARCHAR(255),
    urutan                    SMALLINT NOT NULL DEFAULT 1
);
CREATE INDEX food_record_detail_t_record_ix ON food_record_detail_t (food_record_id);

