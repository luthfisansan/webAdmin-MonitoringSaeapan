-- 4. VIEW (_v)
-- =====================================================================

-- Progres membaca materi wajib per siswa
CREATE VIEW progres_edukasi_v AS
SELECT x.siswa_id,
       x.total_wajib,
       x.dibaca,
       (x.dibaca >= x.total_wajib) AS selesai
FROM (
    SELECT s.siswa_id,
           (SELECT count(*) FROM materi_edukasi_m m
             WHERE m.wajib AND m.aktif) AS total_wajib,
           (SELECT count(*) FROM baca_materi_t b
              JOIN materi_edukasi_m m ON m.materi_edukasi_id = b.materi_edukasi_id
             WHERE b.siswa_id = s.siswa_id AND b.selesai AND m.wajib AND m.aktif) AS dibaca
    FROM siswa_m s
) x;

-- Pretest vs post test per siswa
CREATE VIEW skor_pengetahuan_v AS
SELECT s.siswa_id,
       pre.skor AS skor_pretest,
       post.skor AS skor_posttest,
       (post.skor - pre.skor) AS selisih
FROM siswa_m s
LEFT JOIN (
    SELECT h.siswa_id, h.skor
    FROM hasil_kuesioner_t h
    JOIN kuesioner_m q ON q.kuesioner_id = h.kuesioner_id
    WHERE q.jenis = 'PRETEST' AND h.selesai_pada IS NOT NULL
) pre ON pre.siswa_id = s.siswa_id
LEFT JOIN (
    SELECT h.siswa_id, h.skor
    FROM hasil_kuesioner_t h
    JOIN kuesioner_m q ON q.kuesioner_id = h.kuesioner_id
    WHERE q.jenis = 'POSTTEST' AND h.selesai_pada IS NOT NULL
) post ON post.siswa_id = s.siswa_id;

-- Kepatuhan rencana vs realisasi per hari (sejak mulai sampai hari ini)
--   SESUAI        : semua item food record berstatus SESUAI
--   SEBAGIAN      : sebagian item SESUAI
--   TIDAK_SESUAI  : ada catatan tetapi tidak ada yang sesuai / tidak sarapan
--   BELUM_DICATAT : tidak ada food record pada hari itu
CREATE VIEW kepatuhan_harian_v AS
SELECT pp.peserta_program_id,
       pp.siswa_id,
       d.tanggal,
       ((d.tanggal - pp.tanggal_mulai) / 7 + 1) AS minggu_ke,
       fr.food_record_id,
       CASE
           WHEN fr.food_record_id IS NULL THEN 'BELUM_DICATAT'
           WHEN fr.tidak_sarapan THEN 'TIDAK_SESUAI'
           WHEN x.jml_item > 0 AND x.jml_sesuai = x.jml_item THEN 'SESUAI'
           WHEN x.jml_sesuai > 0 THEN 'SEBAGIAN'
           ELSE 'TIDAK_SESUAI'
       END AS status_kepatuhan
FROM peserta_program_t pp
CROSS JOIN LATERAL (
    SELECT g::date AS tanggal
    FROM generate_series(pp.tanggal_mulai::timestamp,
                         LEAST(pp.tanggal_selesai, CURRENT_DATE)::timestamp,
                         interval '1 day') g
) d
LEFT JOIN food_record_t fr
       ON fr.peserta_program_id = pp.peserta_program_id AND fr.tanggal = d.tanggal
LEFT JOIN LATERAL (
    SELECT count(*) AS jml_item,
           count(*) FILTER (WHERE sr.kode = 'SESUAI') AS jml_sesuai
    FROM food_record_detail_t frd
    JOIN status_realisasi_m sr ON sr.status_realisasi_id = frd.status_realisasi_id
    WHERE frd.food_record_id = fr.food_record_id
) x ON TRUE;

CREATE VIEW kepatuhan_mingguan_v AS
SELECT kh.peserta_program_id,
       kh.siswa_id,
       kh.minggu_ke,
       count(*) AS hari_berjalan,
       count(*) FILTER (WHERE kh.status_kepatuhan <> 'BELUM_DICATAT') AS hari_tercatat,
       count(*) FILTER (WHERE kh.status_kepatuhan = 'SESUAI') AS hari_sesuai,
       round(100.0 * count(*) FILTER (WHERE kh.status_kepatuhan = 'SESUAI')
             / NULLIF(count(*), 0), 1) AS persen_kepatuhan
FROM kepatuhan_harian_v kh
GROUP BY kh.peserta_program_id, kh.siswa_id, kh.minggu_ke;

-- Daftar siswa untuk halaman Data siswa & Dashboard web admin
CREATE VIEW siswa_status_v AS
SELECT s.siswa_id,
       pg.nama_lengkap,
       pg.email,
       k.kelas_id,
       k.nama_kelas,
       sa.status_akun_id,
       sa.kode AS status_akun_kode,
       sa.nama AS status_akun_nama,
       EXISTS (SELECT 1 FROM hasil_kuesioner_t h
                 JOIN kuesioner_m q ON q.kuesioner_id = h.kuesioner_id
                WHERE h.siswa_id = s.siswa_id AND q.jenis = 'PRETEST'
                  AND h.selesai_pada IS NOT NULL) AS pretest_selesai,
       EXISTS (SELECT 1 FROM hasil_kuesioner_t h
                 JOIN kuesioner_m q ON q.kuesioner_id = h.kuesioner_id
                WHERE h.siswa_id = s.siswa_id AND q.jenis = 'POSTTEST'
                  AND h.selesai_pada IS NOT NULL) AS posttest_selesai,
       pe.total_wajib AS materi_wajib_total,
       pe.dibaca      AS materi_wajib_dibaca,
       COALESCE((SELECT sq.status FROM sqffq_t sq
                  WHERE sq.siswa_id = s.siswa_id AND sq.tahap = 'AWAL'), 'BELUM') AS sqffq_status,
       kp.hari_sesuai,
       kp.hari_berjalan,
       kp.persen_kepatuhan
FROM siswa_m s
JOIN pengguna_m pg     ON pg.pengguna_id = s.pengguna_id
JOIN kelas_m k         ON k.kelas_id = s.kelas_id
JOIN status_akun_m sa  ON sa.status_akun_id = s.status_akun_id
LEFT JOIN progres_edukasi_v pe ON pe.siswa_id = s.siswa_id
LEFT JOIN (
    SELECT kh.siswa_id,
           count(*) AS hari_berjalan,
           count(*) FILTER (WHERE kh.status_kepatuhan = 'SESUAI') AS hari_sesuai,
           round(100.0 * count(*) FILTER (WHERE kh.status_kepatuhan = 'SESUAI')
                 / NULLIF(count(*), 0), 1) AS persen_kepatuhan
    FROM kepatuhan_harian_v kh
    GROUP BY kh.siswa_id
) kp ON kp.siswa_id = s.siswa_id;

-- Antrean verifikasi: siswa yang sudah selesai edukasi dan menunggu SQ-FFQ
CREATE VIEW antrean_verifikasi_v AS
SELECT v.siswa_id,
       v.nama_lengkap,
       v.nama_kelas,
       v.sqffq_status,
       (SELECT count(*) FROM sqffq_detail_t d
          JOIN sqffq_t sq ON sq.sqffq_id = d.sqffq_id
         WHERE sq.siswa_id = v.siswa_id AND sq.tahap = 'AWAL') AS item_terisi,
       (SELECT count(*) FROM bahan_makanan_m b WHERE b.aktif) AS item_total
FROM siswa_status_v v
WHERE v.status_akun_kode = 'MENUNGGU_VERIFIKASI';

-- Skor konsumsi pangan per kelompok bahan (satu baris per SQ-FFQ x kelompok)
CREATE VIEW sqffq_rekap_v AS
SELECT sq.sqffq_id,
       sq.siswa_id,
       kb.kelompok_bahan_id,
       kb.kode AS kelompok_kode,
       kb.nama AS kelompok_nama,
       count(d.sqffq_detail_id) AS jumlah_terisi,
       (SELECT count(*) FROM bahan_makanan_m b2
         WHERE b2.kelompok_bahan_id = kb.kelompok_bahan_id AND b2.aktif) AS jumlah_bahan,
       sum(f.skor) AS total_skor
FROM sqffq_t sq
CROSS JOIN kelompok_bahan_m kb
LEFT JOIN bahan_makanan_m bm ON bm.kelompok_bahan_id = kb.kelompok_bahan_id
LEFT JOIN sqffq_detail_t d   ON d.sqffq_id = sq.sqffq_id AND d.bahan_makanan_id = bm.bahan_makanan_id
LEFT JOIN frekuensi_m f      ON f.frekuensi_id = d.frekuensi_id
GROUP BY sq.sqffq_id, sq.siswa_id, kb.kelompok_bahan_id, kb.kode, kb.nama;

-- Total skor konsumsi pangan (food score) per SQ-FFQ
CREATE VIEW sqffq_skor_v AS
SELECT r.sqffq_id,
       r.siswa_id,
       sum(r.total_skor) AS total_skor,
       sum(r.jumlah_terisi) AS jumlah_terisi
FROM sqffq_rekap_v r
GROUP BY r.sqffq_id, r.siswa_id;

-- Detail food record untuk halaman Detail siswa (rencana vs realisasi)
CREATE VIEW food_record_detail_v AS
SELECT pp.siswa_id,
       pp.peserta_program_id,
       fr.food_record_id,
       fr.tanggal,
       ((fr.tanggal - pp.tanggal_mulai) / 7 + 1) AS minggu_ke,
       fr.jam_makan,
       tm.nama AS tempat,
       fr.tidak_sarapan,
       frd.food_record_detail_id,
       frd.nama_makanan,
       frd.bahan_teks,
       u.nama_urt AS urt,
       frd.jumlah_urt,
       frd.berat_gram,
       frd.keterangan,
       sr.kode AS status_realisasi_kode,
       sr.nama AS status_realisasi_nama
